// scripts/build-icons.mjs
// Builds an inline SVG sprite (src/partials/icons.html) from Font Awesome Free
// SVGs so we don't load the 100 KB Font Awesome CSS + webfont from a CDN.
// Font Awesome Free icons: CC BY 4.0 (https://fontawesome.com/license/free).
// Run: npm run icons   (add names to ICONS to include more)
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const FA = path.join(ROOT, 'node_modules', '@fortawesome', 'fontawesome-free', 'svgs');

// [sprite id, FA style folder, FA file name]
// Only icons that are actually used are included (each adds ~0.5–1 KB to every page).
// Available for later: ['user','solid','user'], ['instagram','brands','instagram'],
// ['youtube','brands','youtube'], ['whatsapp','brands','whatsapp']
const ICONS = [
  ['check-circle', 'solid', 'circle-check'],
  ['facebook-f', 'brands', 'facebook-f'],
];

let symbols = '';
for (const [id, style, file] of ICONS) {
  const svg = await readFile(path.join(FA, style, `${file}.svg`), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--[\s\S]*?-->/g, '');
  symbols += `  <symbol id="i-${id}" viewBox="${viewBox}">${inner.trim()}</symbol>\n`;
}

const out = `<!-- Generated by scripts/build-icons.mjs. Do not edit. Font Awesome Free (CC BY 4.0) -->
<svg xmlns="http://www.w3.org/2000/svg" class="svg-sprite" width="0" height="0" aria-hidden="true" focusable="false">
${symbols}</svg>
`;
await writeFile(path.join(ROOT, 'src', 'partials', 'icons.html'), out);
console.log(`Wrote ${ICONS.length} icons`);
